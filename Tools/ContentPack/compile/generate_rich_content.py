def seeded_shuffle(items, seed_key):
    """Deterministic shuffle using SHA256 seed."""
    lst = list(items)
    h = int(hashlib.sha256(seed_key.encode()).hexdigest()[:16], 16)
    rnd = random.Random(h & 0xffffffff)
    rnd.shuffle(lst)
    return lst

